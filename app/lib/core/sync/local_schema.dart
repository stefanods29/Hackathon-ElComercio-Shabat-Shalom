import 'package:powersync/powersync.dart';

/// Local tables. Synced tables have the same columns as their Sync Streams
/// (`infra/powersync/sync-config.yaml`); `comandos` is the upload queue and `envios` keeps the
/// visible state of every command on this phone only.
const localSchema = Schema([
  Table('zonas', [Column.text('nombre'), Column.text('distrito'), Column.text('actualizado_en')]),
  Table('publicaciones', [
    Column.text('autor_id'),
    Column.text('zona_id'),
    Column.text('tipo'),
    Column.text('categoria'),
    Column.text('titulo'),
    Column.text('descripcion'),
    Column.real('lat'),
    Column.real('lng'),
    Column.text('estado'),
    Column.text('tomada_por_id'),
    Column.integer('version'),
    Column.text('vence_en'),
    Column.text('creado_en'),
    Column.text('actualizado_en'),
  ]),
  // Directory (Phase 1, Lot A part 1). Locations are the public copy (ADR 0010).
  Table('categorias', [
    Column.text('nombre'),
    Column.text('icono'),
    Column.integer('util_en_emergencia'),
    Column.integer('orden'),
  ]),
  Table('servicios', [
    Column.text('proveedor_id'),
    Column.text('zona_id'),
    Column.text('categoria_id'),
    Column.text('titulo'),
    Column.text('descripcion'),
    Column.real('lat'),
    Column.real('lng'),
    Column.integer('radio_cobertura_m'),
    Column.integer('disponible_en_emergencia'),
    Column.text('atributos'),
    Column.integer('total_resenas'),
    Column.real('promedio'),
    Column.real('puntaje_ranking'),
    Column.integer('vistos_buenos_de_la_zona'),
    Column.integer('version'),
    Column.text('actualizado_en'),
  ]),
  Table('proveedores', [
    Column.text('nombre_publico'),
    Column.text('descripcion'),
    Column.text('actualizado_en'),
  ]),
  // Reputation: published reviews never carry their author.
  Table('resenas', [
    Column.text('servicio_id'),
    Column.integer('calificacion'),
    Column.text('comentario'),
    Column.text('publicada_en'),
  ]),
  Table('fotos_resena', [
    Column.text('resena_id'),
    Column.text('archivo_id'),
    Column.integer('orden'),
    Column.integer('ancho'),
    Column.integer('alto'),
    Column.text('blurhash'),
  ]),
  Table('mis_resenas', [
    Column.text('servicio_id'),
    Column.integer('calificacion'),
    Column.text('comentario'),
    Column.text('estado'),
    Column.text('motivo_estado'),
    Column.text('creado_en'),
    Column.text('actualizado_en'),
  ]),
  Table('mis_vistos_buenos', [Column.text('servicio_id'), Column.text('creado_en')]),
  Table('agregados_celda', [
    Column.text('zona_id'),
    Column.text('celda'),
    Column.text('necesidad'),
    Column.integer('cantidad'),
    Column.text('actualizado_en'),
  ]),
  Table('recursos_publicos', [
    Column.text('zona_id'),
    Column.text('tipo'),
    Column.integer('cantidad'),
    Column.text('celda'),
    Column.text('reportado_en'),
    Column.integer('umbral_segundos'),
    Column.text('verificacion'),
    Column.integer('confirmaciones'),
    Column.text('etiqueta_publica'),
    Column.text('fuente_url'),
    Column.integer('oficial'),
    Column.text('verificado_en'),
  ]),
  // Coverage of the zone as the API last confirmed it (Lot B): it lets the neighbor write a request
  // without signal. It lives in the account's encrypted database and goes with it.
  Table.localOnly('cobertura_zona', [
    Column.text('evento_id'),
    Column.integer('habilitada'),
    Column.text('modo'),
    Column.text('revisada_en'),
  ]),
  Table('mis_pedidos_ayuda', [
    Column.text('estado'),
    Column.text('necesidad'),
    Column.text('prioridad'),
    Column.integer('version'),
    Column.text('creado_en'),
    Column.text('cerrado_en'),
  ]),
  Table(
    'historial_mis_pedidos',
    [
      Column.text('pedido_id'),
      Column.text('desde'),
      Column.text('hasta'),
      Column.text('rol'),
      Column.text('ocurrido_en'),
      Column.text('motivo'),
    ],
    indexes: [
      Index('pedido', [IndexedColumn('pedido_id')]),
    ],
  ),
  Table.localOnly('pedidos_propios_cerrados', [
    Column.text('estado'),
    Column.integer('version'),
    Column.text('cerrado_en'),
    Column.text('motivo'),
  ]),
  Table.insertOnly('comandos', [
    Column.text('tipo'),
    Column.text('recurso_id'),
    Column.text('cuerpo'),
    Column.text('clave_idempotencia'),
  ]),
  Table.localOnly('envios', [
    Column.text('tipo'),
    Column.text('recurso_id'),
    Column.text('clave_idempotencia'),
    Column.text('estado'),
    Column.integer('intentos'),
    Column.text('creado_en'),
    Column.text('ultimo_intento_en'),
    Column.text('reintentar_en'),
    Column.text('motivo_codigo'),
    Column.text('motivo_titulo'),
    Column.text('motivo_detalle'),
    Column.text('publicacion_optimista'),
    // Optimistic row of directory and reputation commands (JSON); cleared on a final answer.
    Column.text('optimista'),
  ]),
]);
